package rag.android

import rag.BookReader
import rag.SampleBook
import rag.index.Indexer
import rag.search.Searcher
import rag.store.Goldens
import rag.store.SqliteStore
import rag.store.JdbcSqlDriver
import java.io.File
import java.util.Properties

/**
 * Writes the inputs and expected outputs of the Android instrumented tests (SPEC §15.8) into
 * `args[0]`: the fixture books, `desktop.db` (indexed here, no embeddings), `goldens.properties`
 * and one `<book>.units.txt` per book. Run by `:integration-tests:androidGoldens`.
 */
fun main(args: Array<String>) {
    val out = File(args[0]).apply { deleteRecursively(); mkdirs() }
    val epubs = File(args[1])
    SampleBook.write(out.resolve("sample.pdf"))
    epubs.resolve("sun-tzu_the-art-of-war_lionel-giles.epub").copyTo(out.resolve("art-of-war-se.epub"))
    epubs.resolve("pg132.epub").copyTo(out.resolve("pg132.epub"))

    val goldens = Properties()
    SqliteStore(out.resolve("desktop.db").path, JdbcSqlDriver()).use { store ->
        val indexer = Indexer(store, BookReader())
        Goldens.BOOKS.forEach { name ->
            // Two models per book (SPEC §15.9): the phone must search each with its own vectors.
            val bookId = indexer.index(out.resolve(name), embedder = Goldens.MODEL_A).bookId
            indexer.embed(bookId, Goldens.MODEL_B, embedDim = 256, add = true)
            val lines = Goldens.unitLines(store, bookId)
            out.resolve("$name.units.txt").writeText(lines.joinToString("\n"))
            goldens["$name.bookId"] = bookId.toString()
            goldens["$name.units"] = lines.size.toString()
            goldens["$name.unitsSha256"] = Goldens.sha256(lines.joinToString("\n"))
            goldens["$name.textSha256"] = Goldens.sha256(store.bookText(bookId))
            goldens["$name.chapters"] = Goldens.chapters(store, bookId)
            goldens["$name.strategy"] = store.book(bookId)!!.chapterStrategy
        }
        val searcher = Searcher(store, embedder = null)
        Goldens.QUERIES.forEachIndexed { i, query -> goldens["search.$i"] = Goldens.lexicalKeys(searcher, query) }
        for (model in listOf(Goldens.MODEL_A, Goldens.MODEL_B)) {
            val byModel = Searcher(store, model)
            Goldens.QUERIES.forEachIndexed { i, query -> goldens["vector.${model.model}.$i"] = Goldens.vectorKeys(byModel, query) }
        }
    }
    out.resolve("goldens.properties").outputStream().use { goldens.store(it, "Generated by :integration-tests:androidGoldens") }
    println("Android goldens written to $out")
}
